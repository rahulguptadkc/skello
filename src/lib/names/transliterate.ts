/**
 * Phonetically transliterates an English string into Devanagari script.
 */
export function transliterateToDevanagari(text: string): string {
  if (!text || typeof text !== "string") return "";

  const trimmed = text.trim();
  if (!trimmed) return "";

  // If already Devanagari, return as-is
  if (/[\u0900-\u097F]/.test(trimmed)) {
    return trimmed;
  }

  // Check dictionary first (case-insensitive)
  const normalizedKey = trimmed.toLowerCase().replace(/[^a-z]/g, "");
  if (NAME_DICTIONARY[normalizedKey]) {
    return NAME_DICTIONARY[normalizedKey];
  }

  // Handle multi-word strings
  const words = trimmed.split(/\s+/).filter(Boolean);
  if (words.length > 1) {
    return words.map(transliterateToDevanagari).join(" ");
  }

  const word = normalizedKey;
  if (!word) return trimmed;

  let result = "";
  let i = 0;
  const n = word.length;

  while (i < n) {
    // 1. Check special 3-character consonant clusters
    const c3 = word.substring(i, i + 3);
    const c2 = word.substring(i, i + 2);
    const c1 = word.charAt(i);

    let consonant = "";
    let clusterLen = 0;

    if (CONSONANTS[c3]) {
      consonant = CONSONANTS[c3];
      clusterLen = 3;
    } else if (CONSONANTS[c2]) {
      consonant = CONSONANTS[c2];
      clusterLen = 2;
    } else if (CONSONANTS[c1]) {
      consonant = CONSONANTS[c1];
      clusterLen = 1;
    }

    if (consonant) {
      i += clusterLen;

      // Lookahead for vowel after consonant
      const v2 = word.substring(i, i + 2);
      const v1 = word.charAt(i);

      let matra = "";
      let vowelLen = 0;

      if (VOWEL_MATRAS[v2] !== undefined) {
        matra = VOWEL_MATRAS[v2];
        vowelLen = 2;
      } else if (VOWEL_MATRAS[v1] !== undefined) {
        matra = VOWEL_MATRAS[v1];
        vowelLen = 1;
      }

      if (vowelLen > 0) {
        result += consonant + matra;
        i += vowelLen;
      } else {
        // No vowel immediately following:
        // If at the end of the word, omit halant (inherent 'a' pronounced with schwa deletion in modern Hindi)
        if (i >= n) {
          result += consonant;
        } else {
          // Half-character conjunct halant
          result += consonant + "्";
        }
      }
    } else {
      // Independent vowel or unknown character
      const v2 = word.substring(i, i + 2);
      const v1 = word.charAt(i);

      let indVowel = "";
      let vowelLen = 0;

      if (INDEPENDENT_VOWELS[v2]) {
        indVowel = INDEPENDENT_VOWELS[v2];
        vowelLen = 2;
      } else if (INDEPENDENT_VOWELS[v1]) {
        indVowel = INDEPENDENT_VOWELS[v1];
        vowelLen = 1;
      }

      if (indVowel) {
        result += indVowel;
        i += vowelLen;
      } else {
        result += word.charAt(i);
        i++;
      }
    }
  }

  return result || trimmed;
}
